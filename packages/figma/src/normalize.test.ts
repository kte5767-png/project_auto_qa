import { describe, expect, it } from 'vitest';
import { isAutoGeneratedName, isGenericName, meaningfulName } from './names';
import { elementById, isShown, normalizeFrame, rgbaToHex, topPaint } from './normalize';
import { IMAGE, node, sampleHomeFrame, solid, text } from './testing';
import type { ExportedFrame } from './exportFormat';

const frame = normalizeFrame(sampleHomeFrame());
const get = (id: string) => {
	const e = elementById(frame, id);
	if (e === undefined) throw new Error(`요소 없음: ${id}`);
	return e;
};
const byText = (characters: string) => frame.elements.filter((e) => e.text?.characters === characters);

describe('이름 판단', () => {
	it('자동 생성 이름과 일반명을 구분한다', () => {
		for (const n of [
			'Frame 2085670601',
			'Group 2147233501',
			'Rectangle 3',
			'Vector',
			'Frame 12 copy 2',
			'Mask group'
		]) {
			expect(isAutoGeneratedName(n), n).toBe(true);
		}
		for (const n of ['GNB_bar', 'Promo_card', 'Btn_main(New)', 'Top 10 01'])
			expect(isAutoGeneratedName(n), n).toBe(false);
		for (const n of ['title', 'discription', 'Line', 'bg', 'thumbnail 2']) expect(isGenericName(n), n).toBe(true);
	});

	it('텍스트 레이어 이름이 내용과 같으면 앵커 이름이 아니다', () => {
		expect(meaningfulName('Popular now', 'Popular now')).toBeNull();
		expect(meaningfulName('shelf_title', 'Popular now')).toBe('shelf_title');
		expect(meaningfulName('Frame 1')).toBeNull();
	});
});

describe('normalizeFrame', () => {
	it('프레임 왼쪽 위 기준 좌표로 바꾼다', () => {
		expect(frame.width).toBe(1920);
		expect(frame.height).toBe(1080);
		expect(get('9:root').rect).toEqual({ x: 0, y: 0, width: 1920, height: 1080 });
		expect(get('9:card0').rect).toEqual({ x: 96, y: 220, width: 320, height: 180 });
	});

	it('화면에 걸친 요소는 partial, 완전히 밖이면 clipped', () => {
		expect(get('9:card4').visibility).toBe('visible');
		expect(get('9:card5')).toMatchObject({ visibility: 'partial', visibleRatio: expect.closeTo(0.325, 3) });
		expect(get('9:card6').visibility).toBe('clipped');
		const memo = byText('디자이너 메모')[0];
		expect(memo?.visibility).toBe('clipped');
	});

	it('숨김은 자손까지 전파하고 원인 노드를 기록한다', () => {
		const subtitles = byText('Subtitle');
		expect(subtitles).toHaveLength(7);
		for (const s of subtitles) {
			expect(s.hidden).toBe(true);
			expect(s.hiddenBy).toBe(s.parentId);
			expect(isShown(s)).toBe(false);
		}
	});

	it('내용을 자르는 조상 밖의 자손은 clipped', () => {
		const inner = node('RECTANGLE', { x: 300, y: 0, width: 50, height: 50 });
		const clipper = node(
			'FRAME',
			{ x: 0, y: 0, width: 200, height: 200 },
			{ clipsContent: true, children: [inner] }
		);
		const f: ExportedFrame = {
			pageId: 'p',
			pageName: 'p',
			image: null,
			node: node('FRAME', { x: 0, y: 0, width: 1920, height: 1080 }, { children: [clipper] })
		};
		const n = normalizeFrame(f);
		expect(elementById(n, inner.id)?.visibility).toBe('clipped');
	});

	it('글자 스타일·색·종류·컴포넌트를 요약한다', () => {
		const title = byText('Popular now')[0];
		expect(title?.text).toMatchObject({
			fontSize: 36,
			fontWeight: 600,
			color: { hex: '#FFFFFF', alpha: 1 },
			mixed: false
		});
		expect(title?.kind).toBe('text');
		expect(get('9:top0card').kind).toBe('container');
		const image = elementById(frame, get('9:top0card').childIds[0] ?? '');
		expect(image?.kind).toBe('image');
		const gnb = frame.elements.find((e) => e.name === 'GNB_bar');
		expect(gnb).toMatchObject({ kind: 'instance', inInstance: true, anchorName: 'GNB_bar' });
		expect(byText('Home')[0]?.inInstance).toBe(true);
	});

	it('불투명도는 조상까지 곱한다', () => {
		const child = node('RECTANGLE', { x: 0, y: 0, width: 10, height: 10 }, { opacity: 0.5 });
		const parent = node('FRAME', { x: 0, y: 0, width: 100, height: 100 }, { opacity: 0.5, children: [child] });
		const n = normalizeFrame({
			pageId: 'p',
			pageName: 'p',
			image: null,
			node: node('FRAME', { x: 0, y: 0, width: 1920, height: 1080 }, { children: [parent] })
		});
		expect(elementById(n, child.id)?.style.opacity).toBe(0.25);
	});

	it('같은 입력이면 같은 결과', () => {
		expect(normalizeFrame(sampleHomeFrame())).toEqual(normalizeFrame(sampleHomeFrame()));
	});
});

describe('topPaint / rgbaToHex', () => {
	it('보이는 맨 위 칠을 고른다', () => {
		expect(topPaint([solid(1, 0, 0), { ...solid(0, 1, 0), visible: false }])).toEqual({ hex: '#FF0000', alpha: 1 });
		expect(topPaint([solid(1, 0, 0), IMAGE])).toEqual({ hex: 'image', alpha: 1 });
		expect(topPaint([solid(0, 0, 1, 0.5, 0.5)])).toEqual({ hex: '#0000FF', alpha: 0.25 });
		expect(topPaint([])).toBeNull();
		expect(rgbaToHex({ r: 0.5, g: 0.25, b: 1, a: 1 })).toBe('#8040FF');
	});

	it('글자는 칠이 아니라 글자 색으로 본다', () => {
		const t = normalizeFrame({
			pageId: 'p',
			pageName: 'p',
			image: null,
			node: node(
				'FRAME',
				{ x: 0, y: 0, width: 100, height: 100 },
				{
					children: [text('A', { x: 0, y: 0, width: 10, height: 10 }, { color: { r: 1, g: 0, b: 0, a: 1 } })]
				}
			)
		}).elements[1];
		expect(t?.style.fill).toBeNull();
		expect(t?.text?.color?.hex).toBe('#FF0000');
	});
});
