/**
 * 레이어 이름 판단 (D-011). 실제 파일은 이름 대부분이 자동 생성("Frame 2085670601")이라 매칭에 쓸 수 없다.
 * 자동 생성 이름과 일반명("title", "discription")은 앵커로 쓰지 않는다.
 */

const AUTO_GENERATED =
	/^(frame|group|rectangle|ellipse|line|vector|polygon|star|image|text|component|instance|union|subtract|intersect|exclude|section|slice|arrow|mask group|auto layout|boolean)( \d+)*( copy( \d+)?)?$/i;

const GENERIC =
	/^(title|sub ?title|text|txt|desc|description|discription|label|image|img|icon|ico|bg|background|thumb|thumbnail|container|wrapper|wrap|content|contents|item|items|card|layer|box|area|dim|line|divider)( ?\d+)?$/i;

export function isAutoGeneratedName(name: string): boolean {
	return AUTO_GENERATED.test(name.trim());
}

export function isGenericName(name: string): boolean {
	return GENERIC.test(name.trim());
}

/**
 * 앵커로 쓸 수 있는 이름이면 그대로, 아니면 null.
 * 텍스트 레이어 이름이 글자 내용과 같으면 이름이 아니라 내용이므로 null.
 */
export function meaningfulName(name: string, characters: string | null = null): string | null {
	const trimmed = name.trim();
	if (trimmed === '' || isAutoGeneratedName(trimmed) || isGenericName(trimmed)) return null;
	if (characters !== null && trimmed === characters.trim()) return null;
	return trimmed;
}
